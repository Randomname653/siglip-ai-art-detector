def en(text):
    """German labels from the raw result files -> English; layer labels S@k / G@k / D@k spelled out."""
    t = str(text)
    for a, b in UEBERSETZT:
        t = t.replace(a, b)
    m = re.match(r"^([SGD])@(\d+)$", t)
    if m:
        t = {"S": "so400m", "G": "giant", "D": "so400m"}[m.group(1)] + f" layer {int(m.group(2))} alone"
    return t


def lies(n):
    return json.load(open(os.path.join(DATEN, n), encoding="utf-8"))


def p(x, d=1):
    return f"{100 * x:.{d}f} %"


def tab(kopf, zeilen):
    zahl = re.compile(r"^\**[-+]?[\d.,]+( %|/s)?\**$")
    rechts = [i > 0 and all(zahl.match(str(z[i]).strip()) for z in zeilen) for i in range(len(kopf))]
    out = ["| " + " | ".join(kopf) + " |", "|" + "|".join("---:" if r else "---" for r in rechts) + "|"]
    return out + ["| " + " | ".join(str(c) for c in z) + " |" for z in zeilen]


